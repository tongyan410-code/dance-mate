// 归一化：去标点空白、小写、常见口语与繁简，让关键词更容易命中
function normalize(raw) {
  let q = String(raw || '').toLowerCase();
  q = q.replace(/[\s\u3000，。！？!?、；;：:,.~～…·—\-'"“”‘’（）()【】\[\]《》<>]/g, '');
  const slang = [
    [/肿么办|咋办|咋整/g, '怎么办'],
    [/肿么|咋样|咋/g, '怎么'],
    [/啥|啥子|神马|甚么/g, '什么'],
    [/木有|没得/g, '没有'],
    [/阔以/g, '可以'],
    [/片断/g, '片段'],
    [/录象|录相/g, '录像'],
    [/帐号/g, '账号']
  ];
  for (const [re, to] of slang) q = q.replace(re, to);
  const trad = ['記记', '動动', '練练', '節节', '標标', '準准', '問问', '題题', '視视',
    '頻频', '識识', '會会', '點点', '網网', '傳传', '進进', '緊紧', '張张',
    '難难', '學学', '覺觉', '還还', '費费', '錢钱', '對对', '錄录', '體体', '別别'];
  for (const pair of trad) q = q.split(pair[0]).join(pair[1]);
  return q;
}

function pick(list, key, s) {
  const i = s.variants[key] || 0;
  s.variants[key] = i + 1;
  return list[i % list.length];
}

function detectBodyPart(q) {
  const parts = [
    [/膝盖|膝/, '膝盖'], [/腰/, '腰'], [/肩|肩膀/, '肩膀'],
    [/脚踝|踝/, '脚踝'], [/脖子|颈/, '脖子'], [/背/, '背']
  ];
  for (const [re, name] of parts) if (re.test(q)) return name;
  return null;
}

// 去掉常见虚词/量词，让「你能回答些什么」「要不要换个班」这类口语也能对上关键词。
// 只删固定的几个字，不做跨字重排，所以不会把「打算分两段练」误当成「打分」。
function slim(q) {
  return q.replace(/[的了个些吧啊吗呢着过就还]/g, '');
}

// 打分选最相关的话题，而不是「第一个关键词命中就返回」
function bestIntent(q) {
  const q2 = slim(q);
  let best = null, bestScore = -1;
  for (const it of INTENTS) {
    let hits = 0;
    for (const k of it.kw) if (q.includes(k) || q2.includes(k)) hits += 1;
    if (!hits) continue;
    const sc = hits * 10 + (it.priority || 0);
    if (sc > bestScore) { bestScore = sc; best = it; }
  }
  return best;
}

